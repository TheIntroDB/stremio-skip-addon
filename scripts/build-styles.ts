/**
 * Compiles `src/web/app.css` into `src/web/styles.generated.ts`.
 *
 * The pages inline their CSS, so the compiled stylesheet has to exist as a string before `tsc`
 * runs. Doing it here instead of serving `/app.css` keeps the pages self-contained: the same
 * document works in a test, in `tsx watch`, and in the built image, with no static route and no
 * file read at request time.
 *
 * The generated module is gitignored; every npm script that needs it runs this first.
 */

import { execFileSync } from "node:child_process";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const input = path.join(root, "src", "web", "app.css");
const output = path.join(root, "src", "web", "styles.generated.ts");
const cli = path.join(root, "node_modules", "@tailwindcss", "cli", "dist", "index.mjs");

const workDir = await mkdtemp(path.join(tmpdir(), "tidb-tailwind-"));
try {
  const compiled = path.join(workDir, "app.css");
  execFileSync(process.execPath, [cli, "--input", input, "--output", compiled, "--minify"], {
    stdio: "inherit",
  });
  const css = (await readFile(compiled, "utf8")).trim();
  await writeFile(
    output,
    [
      "// SPDX-License-Identifier: GPL-3.0-or-later",
      "// Copyright (C) 2026 TheIntroDB",
      "",
      "// Generated by scripts/build-styles.ts from src/web/app.css. Do not edit.",
      `export const TAILWIND_CSS: string = ${JSON.stringify(css)};`,
      "",
    ].join("\n"),
  );
} finally {
  await rm(workDir, { recursive: true, force: true });
}
